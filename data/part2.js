<p>这场斗争也深刻地塑造了意大利的政治文化。教皇与皇帝的对立，衍生出了意大利内部的两大政治派别——圭尔夫派和吉伯林派，这两个派别之间的斗争，将成为中世纪晚期意大利政治的一个显著特征。</p>


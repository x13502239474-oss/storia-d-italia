<p>格列高利七世的改革，直接触犯了神圣罗马帝国皇帝亨利四世（Henry IV）的利益。双方围绕叙任权展开了激烈的斗争。亨利四世拒绝服从教皇的命令，甚至试图废黜教皇。作为回应，格列高利七世在1076年对亨利四世处以绝罚（开除教籍），并宣布废黜他的皇位。</p>

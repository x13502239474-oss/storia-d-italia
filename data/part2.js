<p>卡诺萨之后，亨利四世重新积蓄力量，再次与教皇对抗。他率军攻入罗马，迫使格列高利七世流亡，格列高利七世最终客死他乡。然而，教皇与皇帝的斗争并未因此结束，而是在接下来的几代人之间持续进行。</p>
